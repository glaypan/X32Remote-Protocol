#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把 x32sim/fxlib.py 的标定表导出为三端共用的数据文件:

  outputs/fx_calibration.json          规范 JSON (人看/文档引用)
  <ios>/Sources/X32RemoteCore/Model/FxCalibration+Generated.swift
                                      (Swift: 原始字符串内嵌同一份 JSON + Codable)
  <android>/app/src/main/assets/fx_calibration.json
                                      (Android: assets 目录, Gradle 原样打包)

为什么内嵌而不走网络: App 直连真台走的是 **OSC**, 真台没有 HTTP 接口,
参数中文名/量程/枚举选项这些元信息 OSC 协议里根本没有 —— 只能随 App 带。
单一事实来源在模拟器仓 (fxlib.py), 本工具负责同步, 禁止手改生成物。

用法:
  python tools/export_fx_calibration.py            # 生成全部
  python tools/export_fx_calibration.py --check    # 只校验是否过期 (CI 防漂移)
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.dirname(HERE)
sys.path.insert(0, BASE)

from x32sim.fxlib import (FX_CAT_LABEL, FX_ENUM_58, FX_TYPE_ALIAS,  # noqa: E402
                          X32_FX_ALGOS)

IOS_OUT = os.path.join(BASE, "..", "X32Remote-ios", "Sources",
                       "X32RemoteCore", "Model", "FxCalibration+Generated.swift")
# ⚠️ 真正的 Android 仓在**工作区之外**: E:\AI\workbuddy\X32RemoteAndroid
#    (Kotlin 工程, ASCII 路径)。BASE/.. 是工作区根 x32遥控 —— 早年写的是
#    BASE/../X32RemoteAndroid, 结果在工作区里误建了一个只有 assets 的幽灵
#    目录, 真仓从来没收到过 (表现为"导出成功但 Android 侧读不到")。
#    可用 X32_ANDROID_DIR 环境变量覆盖 (CI/别的机器)。
AND_OUT = os.path.join(
    os.environ.get("X32_ANDROID_DIR",
                   os.path.join(BASE, "..", "..", "X32RemoteAndroid")),
    "app", "src", "main", "assets", "fx_calibration.json")
JSON_OUT = os.path.join(BASE, "outputs", "fx_calibration.json")

SOURCE_NOTE = ("UNOFFICIAL X32/M32 OSC REMOTE PROTOCOL (Patrick-Gilles Maillot), "
               "Effects Parameters 章")


def build_payload():
    algos = {}
    for name, d in X32_FX_ALGOS.items():
        params = []
        for p in d["params"]:
            item = {"p": p["p"], "field": p["field"], "label": p["label"],
                    "unit": p["unit"], "kind": p["kind"],
                    "lo": p["lo"], "hi": p["hi"]}
            if p["kind"] == "i":
                item["opts"] = p["opts"]
            params.append(item)
        algos[name] = {"label": d["label"], "cat": d.get("cat", "misc"),
                       "heavy": bool(d.get("heavy")), "n": d["n"],
                       "params": params}
        # 语义别名 (time/predelay/damp) 也导出: 三端做 Tap/同步组要用
        for a in ("time", "predelay", "damp"):
            if a in d:
                algos[name][a] = d[a]
        if "time" in d:
            algos[name]["tmin"] = d["tmin"]
            algos[name]["tmax"] = d["tmax"]
            algos[name]["tunit"] = d.get("tunit", "s")
    return {"version": 1, "source": SOURCE_NOTE, "algos": algos,
            "enum58": list(FX_ENUM_58), "catLabel": dict(FX_CAT_LABEL),
            "alias": dict(FX_TYPE_ALIAS)}


SWIFT_HEAD = '''// AUTO-GENERATED by tools/export_fx_calibration.py — 禁止手改。
// 单一事实来源: X32Simulator/x32sim/fxlib.py (数据源: %s)
// 三端 (iOS/Android/网页) 共用同一份标定表; 改动请改 fxlib.py 后重跑导出工具。
import Foundation

/// X32/M32 效果库全量标定表 (61 种算法 / 886 参数)。
/// 随 App 分发是因为 OSC 协议本身不带参数元数据 (中文名/量程/枚举),
/// 真台也没有 HTTP 接口可问。
public enum FxCalibration {
    /// 内嵌的规范 JSON (与 Android/assets、outputs/fx_calibration.json 逐字节一致)
    public static let json = #"""
%%s
"""#

    public static func load() -> FxLib? {
        guard let data = json.data(using: .utf8) else { return nil }
        return try? JSONDecoder().decode(FxLib.self, from: data)
    }
}
''' % SOURCE_NOTE


def render_swift(payload, json_text):
    # 原始字符串 """..."""# 里唯一能提前终止的是 """ 序列; JSON 紧凑输出中
    # 引号只出现在字符串定界符两侧, 不会出现三连引号 —— 真出现了就大声失败,
    # 别悄悄生成一个编译不过的文件。
    assert '"""' not in json_text, "JSON 内含三连引号, 原始字符串方案需改为普通字符串"
    return SWIFT_HEAD % json_text


def main():
    check_only = "--check" in sys.argv
    payload = build_payload()
    json_text = json.dumps(payload, ensure_ascii=False, sort_keys=False,
                           separators=(",", ":"))
    n_algos = len(payload["algos"])
    n_params = sum(a["n"] for a in payload["algos"].values())

    swift_text = render_swift(payload, json_text)

    targets = [(JSON_OUT, json_text + "\n", "规范 JSON"),
               (IOS_OUT, swift_text, "Swift 生成物"),
               (AND_OUT, json_text + "\n", "Android assets")]
    stale = []
    for path, text, label in targets:
        if not os.path.exists(path):
            stale.append("%s 缺失 (%s)" % (path, label))
            continue
        with open(path, encoding="utf-8") as f:
            if f.read() != text:
                stale.append("%s 过期 (%s)" % (path, label))
    if check_only:
        if stale:
            print("!! 标定表导出物与 fxlib.py 不同步:")
            for s in stale:
                print("   " + s)
            print("   跑 python tools/export_fx_calibration.py 重新生成")
            return 1
        print("标定表导出物同步: %d 算法 / %d 参数" % (n_algos, n_params))
        return 0
    for path, text, label in targets:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("已生成 %-58s %6d 字节 (%s)" % (os.path.relpath(path, BASE),
                                             len(text.encode("utf-8")), label))
    print("共 %d 种算法 / %d 个参数" % (n_algos, n_params))
    return 0


if __name__ == "__main__":
    sys.exit(main())
