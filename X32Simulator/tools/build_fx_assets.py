# -*- coding: utf-8 -*-
"""tools/build_fx_assets.py — 把效果器面板图内嵌成 Python 资源模块。

为什么内嵌: 发行形态是**单文件** x32_simulator.py（在线版 / 桌面版内置内核），
不能依赖外部目录；而图片又不能让页面首屏变大（60+ 张 500KB+），所以做成
`/fx/<path>` 按需取，数据存在 x32sim/fxassets.py 里。

源: web/fx/x32/*.webp（X32 61 种算法）、web/fx/wing/{premium,standard}/*.webp（WING 参考图）
    web/fx/fxlib.json（图鉴元数据，由 tools/export_fx_gallery.py 生成）

产物: x32sim/fxassets.py  →  FX_ASSETS = {"x32/HALL.webp": "<base64>", ...}

用法: python tools/build_fx_assets.py            # 生成
      python tools/build_fx_assets.py --check    # 校验是否过期（回归用）
"""
import base64
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.dirname(HERE)
SRC = os.path.join(BASE, "web", "fx")
OUT = os.path.join(BASE, "x32sim", "fxassets.py")
KEEP = (".webp", ".json")


def collect():
    items = {}
    for root, _dirs, files in os.walk(SRC):
        for f in sorted(files):
            if not f.endswith(KEEP):
                continue
            full = os.path.join(root, f)
            rel = os.path.relpath(full, SRC).replace("\\", "/")
            with open(full, "rb") as fh:
                items[rel] = base64.b64encode(fh.read()).decode("ascii")
    return items


def build_text(items):
    lines = [
        "# -*- coding: utf-8 -*-",
        '"""x32sim/fxassets — 内嵌效果器面板图（base64）',
        "",
        "AUTO-GENERATED by tools/build_fx_assets.py — DO NOT EDIT (禁止手改)",
        "开发源在 web/fx/ 下；改图请换 web/fx 里的 webp 再重跑本工具。",
        "图片来自 X32-Edit 4.4 离线渲染（X32 61 种算法）与 WING 官方 FX 选择页截图，",
        "仅用于「认出这是哪个效果器」，不参与任何参数运算。",
        '"""',
        "",
        "FX_ASSETS = {",
    ]
    for k in sorted(items):
        lines.append('    %r: %r,' % (k, items[k]))
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main():
    items = collect()
    text = build_text(items)
    if not items:
        raise SystemExit("!! web/fx 下没有图片 —— 先跑采集脚本")
    total = sum(len(v) for v in items.values()) * 3 // 4

    if "--check" in sys.argv:
        try:
            with open(OUT, "r", encoding="utf-8") as f:
                cur = f.read()
        except OSError:
            cur = None
        if cur != text:
            print("!! x32sim/fxassets.py 与 web/fx 不同步 —— 跑 python tools/build_fx_assets.py")
            return 1
        print("同步 ✓  (%d 个资源, %.2f MB)" % (len(items), total / 1048576))
        return 0

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("写出 %s  (%d 个资源, %.2f MB)" % (OUT, len(items), total / 1048576))
    return 0


if __name__ == "__main__":
    sys.exit(main())
