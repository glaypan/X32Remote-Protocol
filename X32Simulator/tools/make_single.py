#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把 x32sim/ 开发包合成为**自包含单文件** x32_simulator.py (分发形态)。

为什么需要它: 在线版 (python3 x32_simulator.py)、macOS App (CI 从协议仓拉单文件)
都要求"一个 .py 文件就能跑"。开发用包 (可维护), 分发用单文件 (可部署), 两者由本工具
保持一致 —— 单文件是**生成物, 禁止手改**。

规则 (与模块化方案 §2 一致):
  - 按**拓扑序**拼接 (依赖在前; 有环直接报错, 不会悄悄生成错序文件);
  - 剥离全部相对导入 (`from .x import y`) —— 拼接后本就在同一命名空间;
  - stdlib 导入合并去重后统一置顶 (拼接后顺序无关, 全是无副作用的标准库);
  - 产物头部写 AUTO-GENERATED 警告 + 包 docstring;
  - 生成后自动做语法检查。

用法: python tools/make_single.py            # 生成仓库根目录的 x32_simulator.py
      python tools/make_single.py --check    # 只校验不写盘 (CI 可用来防漂移)
"""
import ast
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.dirname(HERE)
PKG = os.path.join(BASE, "x32sim")
OUT = os.path.join(BASE, "x32_simulator.py")

# 模块搬运时的开发形态注释 (合成后无意义, 剥掉)
DEV_BANNER = re.compile(
    r"^# -{10,}\n# 以下代码自 x32_simulator\.py 逐字搬运.*?\n# -{10,}\n",
    re.MULTILINE)

REL_IMPORT = re.compile(r"^\s*from\s+\.")


def modules():
    return sorted(f[:-3] for f in os.listdir(PKG)
                  if f.endswith(".py") and f not in ("__init__.py", "__main__.py"))


def dep_graph():
    """模块 -> 它 import 的本包模块 (只看顶层, 延迟导入不成环)。"""
    g = {}
    for m in modules():
        with open(os.path.join(PKG, m + ".py"), "r", encoding="utf-8") as f:
            tree = ast.parse(f.read())
        deps = set()
        for node in tree.body:
            if isinstance(node, ast.ImportFrom) and node.level == 1 and node.module:
                if node.module in modules():
                    deps.add(node.module)
        g[m] = deps
    return g


def topo_order(g):
    """Kahn 拓扑序; 有环时把环上的节点报出来。"""
    indeg = {m: 0 for m in g}
    for m, deps in g.items():
        for d in deps:
            indeg[m] += 1
    ready = sorted([m for m, d in indeg.items() if d == 0])
    order = []
    while ready:
        m = ready.pop(0)
        order.append(m)
        for other, deps in g.items():
            if m in deps:
                indeg[other] -= 1
                if indeg[other] == 0:
                    ready.append(other)
                    ready.sort()
    if len(order) != len(g):
        cyclic = [m for m in g if m not in order]
        raise SystemExit("!! 模块依赖有环, 无法合成: %s" % ", ".join(cyclic))
    return order


def collect_stdlib(order):
    """各模块的 stdlib 导入 → 合并去重 (http.server 的多个名字合成一条)。"""
    plain, froms = [], {}
    for m in order:
        with open(os.path.join(PKG, m + ".py"), "r", encoding="utf-8") as f:
            tree = ast.parse(f.read())
        for node in tree.body:
            if isinstance(node, ast.Import):
                for a in node.names:
                    stmt = "import %s" % a.name + (" as %s" % a.asname if a.asname else "")
                    if stmt not in plain:
                        plain.append(stmt)
            elif isinstance(node, ast.ImportFrom) and node.level == 0:
                key = node.module
                names = froms.setdefault(key, [])
                for a in node.names:
                    if a.name not in names:
                        names.append(a.name)
    lines = list(plain)
    for mod, names in froms.items():
        lines.append("from %s import %s" % (mod, ", ".join(sorted(names))))
    return lines


def strip_module(src):
    """剥掉相对导入与开发形态注释, 返回剩余行。"""
    out = []
    for ln in src.splitlines():
        if REL_IMPORT.match(ln):
            # 只剥**单行**导入。多行括注导入必须报错退出, 不能只剥第一行 ——
            # 续行会以裸表达式留在文件里, 拼出来的单文件语法错误 (曾经的坑:
            # 判断只认"行尾是 (", 而括号后换行的写法行尾是逗号, 于是漏判)。
            body = ln.strip()
            if "(" in body and ")" not in body:
                raise SystemExit("!! 多行相对导入不支持, 请改成单行: %s" % body)
            if body.count("(") != body.count(")"):
                raise SystemExit("!! 相对导入括号不配对: %s" % body)
            continue
        out.append(ln)
    text = "\n".join(out)
    text = DEV_BANNER.sub("", text)
    return text.strip("\n")


def package_docstring():
    with open(os.path.join(PKG, "__init__.py"), "r", encoding="utf-8") as f:
        doc = ast.get_docstring(ast.parse(f.read()))
    if not doc:
        raise SystemExit("!! x32sim/__init__.py 没有 docstring")
    return doc


def check_webassets_fresh():
    """webassets.py 必须与 web/ 同步 —— 否则会悄悄发出旧页面。"""
    sys.path.insert(0, HERE)
    try:
        import build_web
        _, page = build_web.build_text()
        cur = build_web.load_current()
        if cur is None or getattr(cur, "WEB_PAGE", None) != page:
            raise SystemExit("!! x32sim/webassets.py 与 web/ 不同步 —— 先跑 "
                             "python tools/build_web.py 再生成单文件")
    finally:
        sys.path.remove(HERE)


def build():
    check_webassets_fresh()
    g = dep_graph()
    order = topo_order(g)
    imps = collect_stdlib(order)

    parts = [
        "#!/usr/bin/env python3",
        "# -*- coding: utf-8 -*-",
        "#",
        "# AUTO-GENERATED by tools/make_single.py — DO NOT EDIT (禁止手改)",
        "# 开发源在 x32sim/ 包; 改行为请改包后重新生成:",
        "#     python tools/make_single.py",
        "#",
    ]
    doc = package_docstring()
    parts.append('"""%s"""' % doc)
    parts.append("")
    parts.extend(imps)
    for m in order:
        with open(os.path.join(PKG, m + ".py"), "r", encoding="utf-8") as f:
            body = strip_module(f.read())
        parts.append("")
        parts.append("")
        parts.append("# " + "=" * 66)
        parts.append("# ==== x32sim/%s.py" % m)
        parts.append("# " + "=" * 66)
        if body:
            parts.append(body)
    parts.append("")
    parts.append("")
    parts.append('if __name__ == "__main__":')
    parts.append("    main()")
    parts.append("")
    return "\n".join(parts), order


def main():
    text, order = build()
    # 语法检查 (合成错了要在这里炸, 不要等运行时)
    try:
        ast.parse(text)
    except SyntaxError as e:
        raise SystemExit("!! 合成结果语法错误: %s (行 %s)" % (e.msg, e.lineno))

    if "--check" in sys.argv:
        with open(OUT, "r", encoding="utf-8") as f:
            cur = f.read()
        if cur != text:
            print("!! x32_simulator.py 与 x32sim/ 包不同步 —— 请跑 python tools/make_single.py")
            return 1
        print("同步 ✓  (%d 个模块, %d 行)" % (len(order), len(text.splitlines())))
        return 0

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("已生成 x32_simulator.py: %d 个模块, %d 行 (拓扑序: %s)"
          % (len(order), len(text.splitlines()), " → ".join(order)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
