#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把 web/ 下的源文件合成为 x32sim/webassets.py (内嵌网页 + PWA 资源)。

为什么: 页面曾是 Python 三引号字符串里的一坨 (2098 行) —— 没有语法检查、没有跳转,
改一行要跑整个页面, 而且 `\n` 转义坑真实咬过一口 (JS 字符串被求值成换行, 整页白屏)。
拆成 web/ 三文件后可以正常编辑; 发布形态仍然**零外部请求** (全部内联进一个字符串)。

源文件 → 产物:
    web/index.html             页面骨架 (CSS/JS 用 <link>/<script src> 占位)
    web/app.css                样式
    web/app.js                 脚本 (单文件, 按注释分段)
    web/icon.svg               PWA 图标
    web/manifest.webmanifest   PWA 清单
    web/sw.js                  Service Worker (只满足可安装性, 不缓存任何内容)
                              ↓ 内联
    x32sim/webassets.py        PWA_ICON / PWA_MANIFEST / PWA_SERVICE_WORKER / WEB_PAGE

用法: python tools/build_web.py           # 生成
      python tools/build_web.py --check   # 只校验 webassets.py 是否与 web/ 同步
"""
import ast
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.dirname(HERE)
WEB = os.path.join(BASE, "web")
OUT = os.path.join(BASE, "x32sim", "webassets.py")

CSS_LINK = '<link rel="stylesheet" href="/app.css">'
JS_TAG = '<script src="/app.js"></script>'


def read(name):
    with open(os.path.join(WEB, name), "r", encoding="utf-8") as f:
        return f.read()


def literal(text):
    """Python 字符串字面量: 优先可读的三引号 (原生换行), 否则退回 repr。"""
    if '"""' not in text and not text.endswith('"') and not text.endswith("\\"):
        return 'r"""%s"""' % text
    return repr(text)


def assemble():
    html, css, js = read("index.html"), read("app.css"), read("app.js")
    if html.count(CSS_LINK) != 1 or html.count(JS_TAG) != 1:
        raise SystemExit("!! index.html 里 CSS/JS 占位符必须各出现一次 "
                         "(css=%d js=%d)" % (html.count(CSS_LINK), html.count(JS_TAG)))
    page = html.replace(CSS_LINK, "<style>\n%s</style>" % css)
    page = page.replace(JS_TAG, "<script>\n%s</script>" % js)
    return page


def build_text():
    page = assemble()
    parts = [
        "# -*- coding: utf-8 -*-",
        '"""x32sim/webassets — 内嵌网页与 PWA 资源',
        "",
        "AUTO-GENERATED by tools/build_web.py — DO NOT EDIT (禁止手改)",
        "开发源在 web/ 下 (index.html + app.css + app.js + icon.svg + manifest + sw.js),",
        "改页面请改那边, 然后跑: python tools/build_web.py",
        '"""',
        "",
        "",
        "PWA_ICON = " + literal(read("icon.svg")),
        "",
        "PWA_MANIFEST = " + literal(read("manifest.webmanifest")),
        "",
        "PWA_SERVICE_WORKER = " + literal(read("sw.js")),
        "",
        "WEB_PAGE = " + literal(page),
        "",
    ]
    return "\n".join(parts), page


def load_current():
    if not os.path.exists(OUT):
        return None
    spec = importlib.util.spec_from_file_location("_wa_cur", OUT)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def main():
    text, page = build_text()
    # 语法 + 往返自检: 生成的文件 import 回来必须等于刚拼装的页面
    try:
        ast.parse(text)
    except SyntaxError as e:
        raise SystemExit("!! 生成的 webassets.py 语法错误: %s (行 %s)" % (e.msg, e.lineno))

    if "--check" in sys.argv:
        cur = load_current()
        with open(OUT, "r", encoding="utf-8") as f:
            if f.read() != text:
                print("!! webassets.py 与 web/ 不同步 —— 请跑 python tools/build_web.py")
                return 1
        if cur is not None and getattr(cur, "WEB_PAGE", None) != page:
            print("!! WEB_PAGE 往返不一致 (生成物被手改过?)")
            return 1
        print("同步 ✓  (WEB_PAGE %d 字符)" % len(page))
        return 0

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    # 落盘后再 import 一次, 确认字面量转义没有吃掉任何字符
    cur = load_current()
    ok = all(getattr(cur, k, None) == v for k, v in (
        ("WEB_PAGE", page),
        ("PWA_ICON", read("icon.svg")),
        ("PWA_MANIFEST", read("manifest.webmanifest")),
        ("PWA_SERVICE_WORKER", read("sw.js")),
    ))
    if not ok:
        raise SystemExit("!! 往返校验失败: 生成文件 import 回来与源文件不一致")
    print("已生成 x32sim/webassets.py: WEB_PAGE %d 字符 (往返校验通过)" % len(page))
    return 0


if __name__ == "__main__":
    sys.exit(main())
